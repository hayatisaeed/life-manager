export interface FormatSettings {
  language: 'en' | 'fa';
  calendar: 'gregorian' | 'jalali';
  digits: 'latin' | 'persian';
}
const locale = (settings: FormatSettings) =>
  `${settings.language}-u-ca-${settings.calendar === 'jalali' ? 'persian' : 'gregory'}-nu-${settings.digits === 'persian' ? 'arabext' : 'latn'}`;
export function formatDate(date: string, settings: FormatSettings): string {
  return new Intl.DateTimeFormat(locale(settings), { dateStyle: 'long', timeZone: 'UTC' }).format(
    new Date(`${date}T12:00:00.000Z`),
  );
}
export function formatNumber(value: number, settings: FormatSettings): string {
  return new Intl.NumberFormat(locale(settings)).format(value);
}
export function formatMoney(amount: number, currency: string, settings: FormatSettings): string {
  const formatter = new Intl.NumberFormat(locale(settings), { style: 'currency', currency });
  const digits = formatter.resolvedOptions().maximumFractionDigits ?? 2;
  return formatter.format(amount / 10 ** digits);
}
export function localDateAt(millis: number): string {
  const parts = new Intl.DateTimeFormat('en', {
    calendar: 'gregory',
    numberingSystem: 'latn',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).formatToParts(new Date(millis));
  const value = (type: string) => parts.find((part) => part.type === type)?.value ?? '';
  return `${value('year')}-${value('month')}-${value('day')}`;
}

export function formatInstant(instant: string, settings: FormatSettings): string {
  return new Intl.DateTimeFormat(locale(settings), {
    dateStyle: 'medium',
    timeStyle: 'short',
  }).format(new Date(instant));
}
export function instantInput(instant: string): string {
  const date = new Date(instant);
  return new Date(date.getTime() - date.getTimezoneOffset() * 60000).toISOString().slice(0, 16);
}
